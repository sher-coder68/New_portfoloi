import nodemailer from 'nodemailer';

/**
 * Sends email notifications for new portfolio inquiries.
 * Gracefully falls back to console logger if SMTP credentials are not configured.
 */
export const sendContactNotification = async ({ name, email, subject, message, id }) => {
  const recipient = process.env.NOTIFICATION_EMAIL || 'khansher68u@gmail.com';
  const hasSmtpConfig = process.env.SMTP_HOST && process.env.SMTP_USER && process.env.SMTP_PASS;

  const emailSubject = `[Portfolio Inquiry] ${subject} - from ${name}`;
  const textContent = `
You have received a new contact submission from your portfolio website:

From: ${name} (${email})
Subject: ${subject}
Date: ${new Date().toLocaleString()}

Message Content:
----------------------------------------
${message}
----------------------------------------

Manage this inquiry in your Portfolio Admin Panel.
  `;

  if (!hasSmtpConfig) {
    console.log(`[Email Notification Simulated - SMTP not configured in .env]`);
    console.log(`To: ${recipient}`);
    console.log(`Subject: ${emailSubject}`);
    console.log(`Content:\n${textContent}`);
    return { success: true, simulated: true };
  }

  try {
    const transporter = nodemailer.createTransport({
      host: process.env.SMTP_HOST,
      port: Number(process.env.SMTP_PORT) || 587,
      secure: Number(process.env.SMTP_PORT) === 465,
      auth: {
        user: process.env.SMTP_USER,
        pass: process.env.SMTP_PASS,
      },
    });

    const info = await transporter.sendMail({
      from: `"${name} via Khan Sher Portfolio" <${process.env.SMTP_USER}>`,
      to: recipient,
      replyTo: email,
      subject: emailSubject,
      text: textContent,
      html: `
        <div style="font-family: Arial, sans-serif; max-width: 600px; padding: 20px; background-color: #0b0f17; color: #f1f5f9; border-radius: 12px; border: 1px solid #14b8a6;">
          <h2 style="color: #2dd4bf; margin-top: 0;">New Contact Form Submission</h2>
          <p><strong>From:</strong> ${name} (<a href="mailto:${email}" style="color: #5eead4;">${email}</a>)</p>
          <p><strong>Subject:</strong> ${subject}</p>
          <p><strong>Date:</strong> ${new Date().toLocaleString()}</p>
          <div style="background-color: #161f2e; padding: 15px; border-radius: 8px; border-left: 4px solid #14b8a6; margin: 20px 0;">
            <p style="white-space: pre-line; margin: 0; color: #e2e8f0;">${message}</p>
          </div>
          <p style="font-size: 12px; color: #94a3b8;">This message was automatically generated by Khan Sher's Portfolio API.</p>
        </div>
      `,
    });

    console.log(`[Email Notification Sent] Message ID: ${info.messageId}`);
    return { success: true, messageId: info.messageId };
  } catch (err) {
    console.error(`[Email Notification Error] ${err.message}`);
    // Do not fail form submission if email notification encounters an SMTP error
    return { success: false, error: err.message };
  }
};

